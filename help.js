function buildHelpNav() {
  var nav = document.getElementById('helpNav');
  if (!nav) return;
  var html = '';
  for (var i = 0; i < HELP_SECTIONS.length; i++) {
    var s = HELP_SECTIONS[i];
    html += '<div class="help-nav-item' + (i === 0 ? ' active' : '') +
      '" data-help-section="' + s.id + '" onclick="showHelpSection(\'' + s.id + '\')">' +
      s.title + '</div>';
  }
  nav.innerHTML = html;
}

function showHelpSection(id) {
  var section = null;
  for (var i = 0; i < HELP_SECTIONS.length; i++) {
    if (HELP_SECTIONS[i].id === id) {
      section = HELP_SECTIONS[i];
      break;
    }
  }
  if (!section) return;

  var contentEl = document.getElementById('helpContent');
  if (contentEl) {
    contentEl.innerHTML = section.content;
    contentEl.scrollTop = 0;
  }

  var items = document.querySelectorAll('.help-nav-item');
  for (var j = 0; j < items.length; j++) {
    if (items[j].getAttribute('data-help-section') === id) {
      items[j].classList.add('active');
    } else {
      items[j].classList.remove('active');
    }
  }
}

function openHelp() {
  var overlay = document.getElementById('helpOverlay');
  if (!overlay) return;
  var nav = document.getElementById('helpNav');
  if (nav && !nav.children.length) buildHelpNav();
  var contentEl = document.getElementById('helpContent');
  if (contentEl && !contentEl.innerHTML) showHelpSection(HELP_SECTIONS[0].id);
  overlay.style.display = 'flex';
  setTimeout(function() { overlay.classList.add('visible'); }, 50);
}

function closeHelp() {
  var overlay = document.getElementById('helpOverlay');
  if (!overlay) return;
  overlay.classList.remove('visible');
  setTimeout(function() { overlay.style.display = 'none'; }, 300);
}

function initHelp() {
  var openBtn = document.getElementById('helpOpenBtn');
  if (openBtn) openBtn.addEventListener('click', openHelp);

  var closeBtn = document.getElementById('helpCloseBtn');
  if (closeBtn) closeBtn.addEventListener('click', closeHelp);

  var overlay = document.getElementById('helpOverlay');
  if (overlay) {
    overlay.addEventListener('click', function(e) {
      if (e.target === overlay) closeHelp();
    });
  }

  document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape') {
      var ov = document.getElementById('helpOverlay');
      if (ov && ov.style.display !== 'none') closeHelp();
    }
  });

  buildHelpNav();
  showHelpSection(HELP_SECTIONS[0].id);
}

initHelp();
